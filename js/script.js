let currentModalId = 1;

const storyModal = document.getElementById('story-modal');
const closeModal = document.getElementById('close-modal');
const nextBtn = document.getElementById('next-btn');
const modalNumeral = document.getElementById('modal-numeral');
const modalTitle = document.getElementById('modal-title');
const modalText = document.getElementById('modal-text');

function openStoryModal(id) {
    currentModalId = id;
    const chapter = storyChapters.find(c => c.id === id);
    if (!chapter) return;

    discovered.add(id);

    modalNumeral.textContent = `FRAGMENTO ${chapter.numeral}`;
    modalTitle.textContent = chapter.title;
    modalText.innerHTML = chapter.text.split('\n\n').map(p => `<p>${p}</p>`).join('');

    storyModal.classList.remove('pointer-events-none', 'opacity-0');
    const panel = storyModal.querySelector('.glass-modal');
    panel.classList.remove('scale-95');
    panel.classList.add('scale-100');

    gsap.to(clockGroup.rotation, { y: clockGroup.rotation.y + 0.5, duration: 1.5, ease: "power2.out" });
}

function closeStoryModal() {
    const panel = storyModal.querySelector('.glass-modal');
    panel.classList.remove('scale-100');
    panel.classList.add('scale-95');
    storyModal.classList.add('opacity-0', 'pointer-events-none');
}

closeModal.addEventListener('click', closeStoryModal);
storyModal.addEventListener('click', (e) => { if (e.target === storyModal) closeStoryModal(); });

nextBtn.addEventListener('click', () => {
    let nextId = currentModalId + 1;
    if (nextId > 12) nextId = 1;
    openStoryModal(nextId);
});

// --- LOOP DE ANIMAÇÃO ---
const clock = new THREE.Clock();

function animate() {
    requestAnimationFrame(animate);
    const time = clock.getElapsedTime();

    if (sceneState === 'DOOR') {
        doorGroup.position.y = Math.sin(time * 1.5) * 0.22;
        doorGroup.rotation.y = Math.sin(time * 0.8) * 0.18;
        doorGroup.rotation.x = Math.cos(time * 0.6) * 0.1;
        irisMesh.scale.setScalar(1 + Math.sin(time * 3.5) * 0.12);

        doorRings.forEach((r, idx) => {
            r.mesh.rotation.x += r.speedX;
            r.mesh.rotation.z += r.speedZ;
        });

        particles.rotation.y = time * 0.02;

        raycaster.setFromCamera(mouse, camera);
        const intersects = raycaster.intersectObjects([doorMesh]);
        if (intersects.length > 0) {
            document.body.style.cursor = 'pointer';
            gsap.to(doorGroup.scale, { x: 1.12, y: 1.12, z: 1.12, duration: 0.3 });
        } else {
            document.body.style.cursor = 'default';
            gsap.to(doorGroup.scale, { x: 1, y: 1, z: 1, duration: 0.3 });
        }
    } else if (sceneState === 'WHEEL') {
        rotatingRings.forEach(ringObj => {
            ringObj.mesh.rotation.x += ringObj.speedX;
            ringObj.mesh.rotation.y += ringObj.speedY;
            ringObj.mesh.rotation.z += ringObj.speedZ;
        });

        numeralRingGroup.rotation.z = time * 0.035;
        clockGroup.rotation.y = time * 0.02;
        particles.rotation.y = time * 0.015;

        numeralMeshes.forEach(m => { m.quaternion.copy(camera.quaternion); });

        raycaster.setFromCamera(mouse, camera);
        const intersects = raycaster.intersectObjects(numeralMeshes);

        if (intersects.length > 0) {
            const hit = intersects[0].object;
            if (hoveredObject !== hit) {
                if (hoveredObject) gsap.to(hoveredObject.scale, { x: 1, y: 1, z: 1, duration: 0.2 });
                hoveredObject = hit;
                gsap.to(hoveredObject.scale, { x: 1.45, y: 1.45, z: 1.45, duration: 0.2 });
                document.body.style.cursor = 'pointer';
            }
        } else {
            if (hoveredObject) {
                gsap.to(hoveredObject.scale, { x: 1, y: 1, z: 1, duration: 0.2 });
                hoveredObject = null;
                document.body.style.cursor = 'default';
            }
        }
    }

    controls.update();
    renderer.render(scene, camera);
}

window.addEventListener('resize', () => {
    camera.aspect = window.innerWidth / window.innerHeight;
    camera.updateProjectionMatrix();
    renderer.setSize(window.innerWidth, window.innerHeight);
});

window.onload = function () { animate(); };